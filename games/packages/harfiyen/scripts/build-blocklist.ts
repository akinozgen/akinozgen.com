/**
 * Writes src/blocklist.ts, the words a player's name may not be, from two
 * published Turkish lists:
 *
 *   ooguz/turkce-kufur-karaliste  karaliste.txt   CC BY-SA 4.0
 *   LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words  tr   CC BY 4.0
 *
 *   node scripts/build-blocklist.ts karaliste.txt tr
 *
 * Words are folded the way names are checked (`foldWord` in src/names.ts),
 * and a few everyday words the lists hold for one of their senses are let
 * through (EVERYDAY), since a name like "Ana Arı" or "Kaka" is no insult,
 * as are teasing words a player may take for a nickname (MILD).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { foldWord } from "../src/fold.ts";

/** Everyday words the lists hold for one of their senses; as a name, or in one, they insult nobody. */
const EVERYDAY = new Set(
  `ana anas ananas ananat anasır anasıl cim emi eben sie kaka saxo bacn cif ağ as aş hür öç öcü cuk dolu gibisi
  gibisinden gibisiz oğlan oğlanevi kayyum kayyumluk revizyonist saksonya sekiş sökük sökükçü söküm sökümcü
  sökümcülük söküş sokum sokuş malak malakit malakar malakari dalama dalamak dalaman kasara çıkar çıkarma çıkarmak
  çıkarım çıkartma çıkartmak çıkartı düdük düdükçü düdüklü penisilin silik silikon silikat sistem sistematik
  allahsız abaza abazaca oğlancık boşalmak yalama yalamak`
    .split(/\s+/)
    .filter(Boolean)
    .map((word) => foldWord(word)),
);

/**
 * Teasing, not swearing: words the lists count as insults that a player may
 * well call themself ("Atkafası", "Salak Kedi"). What stays out is swearing,
 * sex, slurs and the heavy insults.
 */
const MILD = new Set(
  `atkafası atkafasi salak salakça aptal aptalca mal ahmak gerzek gerzekçe dangalak dangalakça dingil öküz beyinsiz
  kafasız manyak manyakça embesil ebleh zibidi hödük angut dallama dönek kaypak yılışık feriştah cenabet dinsiz
  basur avrat osuruk osurmak geberik gebermek lavuk avel`
    .split(/\s+/)
    .filter(Boolean)
    .map((word) => foldWord(word)),
);

const sources = process.argv.slice(2);
if (sources.length === 0) throw new Error("usage: build-blocklist.ts <list> [<list> …]");
const words = new Set<string>();
for (const source of sources) {
  for (const line of readFileSync(source, "utf8").split(/\r?\n/)) {
    const word = foldWord(line);
    if (word.length >= 2 && !EVERYDAY.has(word) && !MILD.has(word)) words.add(word);
  }
}
const sorted = [...words].sort();
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(
  join(here, "../src/blocklist.ts"),
  `// Generated by scripts/build-blocklist.ts; do not edit by hand.
// Words a player's name may not hold, folded (see fold.ts). From
// ooguz/turkce-kufur-karaliste (CC BY-SA 4.0) and LDNOOBW's Turkish list (CC BY 4.0).
export const BLOCKLIST: readonly string[] = ${JSON.stringify(sorted)};
`,
);
console.log(`blocklist.ts: ${sorted.length} words`);
